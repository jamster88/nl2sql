"""The Repair Agent: turn a failure into a hint, and only rarely into a model call.

Section 6.3 of `multi-agent_arch_specs/Multi-Agent_NL2SQL_arch4.md`. One agent
writes SQL and it is not this one. Every gate in stage 3 -- the Static
Validator, the Planner Gate, the Safe Executor, the Audit Checker -- reports a
failure as an `Issue`, and this module's whole job is to fill in that issue's
`hint`: the sentence the generator is shown alongside its own rejected query.

The design point is economic. A repair that called the model would double the
model calls of every retry, and with `MAX_ATTEMPTS = 4` that is three extra
round trips on exactly the questions that are already slow. But most failures
do not need a model to diagnose. Postgres says `column "store_nam" does not
exist`; the pruned schema says the column is `store_name`; the gap between
those two facts is a trigram match, not an act of reasoning. So this module
classifies deterministically first and calls the model **only** when nothing in
the spec's table matches -- which is what `repair_hint` returning a model-call
count of 0 or 1 is there to let the benchmark prove.

The classifier matches on Postgres' own message text, which arrives verbatim
from the planner or the driver, because that text is the most reliable thing in
the pipeline: it is generated by the server, not by a model, and its phrasing
is stable across releases in a way that nothing else here is.

Two things this module deliberately does not do. It does not write SQL, not
even a fragment large enough to paste: a hint that contains a query is a query
the generator will copy without understanding, and the generator is the agent
holding the question, the schema and the examples. And it does not invent
specifics. When `history` shows the same error twice it says so, because that
is derivable; it does not guess *why* two attempts failed the same way.
"""

from __future__ import annotations

import difflib
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, replace
from typing import Any, Protocol

from .state import AUDIT, PLANNER, STATIC, Attempt, Issue

#: How much SQL to quote around a syntax error, per side. The spec asks for
#: "the 40 characters around n"; two of these is that.
CONTEXT_CHARS = 20

#: At most this many near-miss names are offered. A longer list reads as "pick
#: one", which is how a generator ends up inventing a fourth.
MAX_SUGGESTIONS = 3

#: difflib's similarity floor for a suggestion. 0.6 is what `literal_min_score`
#: already uses for the Literal Matcher, so the two agents agree on what counts
#: as a near miss.
NEAR_MISS_CUTOFF = 0.6

#: Both the cost gate and the timeout mean the same thing about the query: it
#: touches far more rows than the question needs.
COST_HINT = (
    "The plan is a cross join or an unfiltered scan; join on the declared keys and "
    "filter on fiscal_year."
)

#: What the generator is told when neither the classifier nor a model produced
#: anything. It is deliberately about *process*, not content: pretending to
#: diagnose an error we did not recognise would be worse than admitting it.
GENERIC_HINT = (
    "This error is not one the repair classifier recognises. Re-read it against the schema "
    "block, work out which part of the query it refers to, and change that part -- do not "
    "re-send the same query."
)

_DIAGNOSIS_SYSTEM = (
    "You diagnose a failed SQL query for the engineer who will rewrite it.\n"
    "Reply with one short paragraph of prose: what the error means about this query, and "
    "what to do differently.\n"
    "Do not write SQL. Another agent writes the query; your paragraph is all it gets."
)


class SupportsInvoke(Protocol):
    """The sliver of a chat model this module uses.

    Typed as a Protocol rather than imported from langchain so that `repair.py`
    stays testable with any object exposing `.invoke()`, and so that importing
    the classifier costs nothing.
    """

    def invoke(self, messages: Any) -> Any: ...


@dataclass(frozen=True)
class _Failure:
    """Everything a classification rule is allowed to look at."""

    source: str
    message: str
    schema: str
    allowed_tables: tuple[str, ...]
    #: The SQL that produced this failure, recovered from `history`. Empty when
    #: the caller kept no history, which costs the syntax rule its quotation
    #: and nothing else.
    sql: str

    @property
    def lowered(self) -> str:
        return self.message.lower()


# --- public API --------------------------------------------------------------


def classify(
    issue: Issue,
    *,
    schema: str = "",
    allowed_tables: Iterable[str] = (),
    history: Sequence[Attempt] = (),
) -> str | None:
    """The hint for one issue, or None when only a model can diagnose it.

    `schema` is the rendered schema block the generator was given (the v3
    `schema_and_samples` format); it is where the column suggestions come from.
    `allowed_tables` is the validator's allowlist, which is where the table
    suggestions come from. `history` supplies the failed SQL -- and, when an
    error has already been seen, the line that says so.

    Returning None is a real answer, not a failure: it routes the issue to the
    one model call this stage is allowed.
    """
    failure = _Failure(
        source=issue.source,
        message=issue.message or "",
        schema=schema,
        allowed_tables=tuple(allowed_tables),
        sql=_failed_sql(history),
    )
    for rule in _RULES:
        hint = rule(failure)
        if hint:
            return _repeat_prefix(failure.message, history) + hint
    return None


def repair_hint(
    issues: Sequence[Issue],
    *,
    llm: SupportsInvoke | None = None,
    schema: str = "",
    allowed_tables: Iterable[str] = (),
    history: Sequence[Attempt] = (),
) -> tuple[list[Issue], int]:
    """The issues with their hints filled in, and the model calls that cost.

    The count is the point of the return type: it is 0 whenever the classifier
    recognised *anything*, and at most 1 otherwise. One call covers all the
    unclassified issues together, since they came from one rejected query and a
    model asked about them separately would only repeat itself.

    An issue the classifier could not place, standing beside one it could,
    keeps an empty hint. Its verbatim message is still shown to the generator
    by `Issue.render`, and a generic "think again" next to a specific
    instruction reads as though the specific one were also a guess.

    With no model and nothing classified, the generic hint goes out and the run
    continues. Give-up is the budget's job, not this module's.
    """
    originals = list(issues)
    if not originals:
        return [], 0

    hints = [
        classify(issue, schema=schema, allowed_tables=allowed_tables, history=history)
        for issue in originals
    ]
    if any(hint is not None for hint in hints):
        # `replace` rather than assignment: these same Issue objects are held by
        # `attempt_history`, and a hint written in place would rewrite the
        # record of what the earlier attempt was actually told.
        return [
            replace(issue, hint=hint) if hint else replace(issue)
            for issue, hint in zip(originals, hints)
        ], 0

    if llm is None:
        body, calls = GENERIC_HINT, 0
    else:
        body, calls = _diagnose(llm, originals, schema, _failed_sql(history)), 1
    return [
        replace(issue, hint=_repeat_prefix(issue.message or "", history) + body)
        for issue in originals
    ], calls


# --- the classification table (section 6.3) -----------------------------------


def _audit(failure: _Failure) -> str | None:
    """An audit issue is already a diagnosis, written against the real rows.

    The Audit Checker compared the narrative's claims to the result set and
    concluded the SQL was wrong; nothing here can improve on that sentence, so
    it is passed through unchanged.
    """
    if failure.source == AUDIT and failure.message.strip():
        return failure.message.strip()
    return None


def _syntax(failure: _Failure) -> str | None:
    """Quote the SQL around the parser's position.

    "syntax error at or near FORM" is not actionable on a 30-line query with
    four CTEs; the same message with the surrounding twenty characters on each
    side points at one clause.
    """
    if "syntax error" not in failure.lowered:
        return None

    position = _position(failure.message)
    near = re.search(r'at or near ["\']([^"\']+)["\']', failure.message)

    if failure.sql and position is not None and 0 <= position <= len(failure.sql):
        return (
            f'Syntax error here: "{_around(failure.sql, position)}" '
            f"(at character {position + 1}). Fix the syntax at that point."
        )
    # Postgres echoes the offending line itself; when there is no SQL to slice,
    # that echo is the next best quotation.
    line = re.search(r"^LINE \d+:\s*(.+)$", failure.message, re.MULTILINE)
    if line:
        return f'Syntax error here: "{line.group(1).strip()}". Fix the syntax at that point.'
    if near:
        return (
            f'Syntax error here: at or near "{near.group(1)}". Fix the syntax at that point.'
        )
    return "The statement did not parse. Re-send it as one syntactically valid SELECT."


def _missing_column(failure: _Failure) -> str | None:
    """Name the columns the schema actually has, nearest first."""
    match = re.search(
        r'column ["\']?([\w.$]+)["\']? does not exist', failure.message, re.IGNORECASE
    )
    if not match:
        return None

    qualified = match.group(1)
    bare = qualified.rsplit(".", 1)[-1]
    suggestions = _nearest(bare, schema_columns(failure.schema))
    if suggestions:
        return f"`{qualified}` is not a column; the schema has {_quoted(suggestions)}."
    return (
        f"`{qualified}` is not a column in this schema. Use only the column names listed "
        f"under `columns:` in the schema block."
    )


def _missing_table(failure: _Failure) -> str | None:
    """Both ways a table can be wrong: the server's and the allowlist's.

    The Static Validator rejects a table that is out of scope before the
    server ever sees it, and Postgres rejects one that does not exist at all.
    The fix the generator needs is the same sentence either way.
    """
    match = re.search(
        r'relation ["\']?([\w.$]+)["\']? does not exist', failure.message, re.IGNORECASE
    )
    if not match and failure.source == STATIC:
        match = re.search(r"([\w.$]+) is not in scope", failure.message)
    if not match:
        return None

    name = match.group(1)
    bare = name.rsplit(".", 1)[-1]
    # The allowlist is authoritative when the caller has one; the schema block
    # names the same tables and stands in when it does not.
    candidates = list(failure.allowed_tables) or schema_tables(failure.schema)
    suggestions = _nearest(bare, candidates)
    if suggestions:
        return f"`{name}` is not a table you may query; use {_quoted(suggestions)} instead."
    if candidates:
        return (
            f"`{name}` is not a table you may query. The tables in scope are "
            f"{_quoted(candidates[:MAX_SUGGESTIONS])}."
        )
    return f"`{name}` is not a table you may query; use only the tables in the schema block."


def _group_by(failure: _Failure) -> str | None:
    """The commonest aggregate mistake, and one with exactly two fixes."""
    if "must appear in the group by clause" not in failure.lowered:
        return None
    match = re.search(
        r'column ["\']?([\w.$]+)["\']? must appear', failure.message, re.IGNORECASE
    )
    if match:
        return (
            f"`{match.group(1)}` is selected but neither grouped nor aggregated; add it to "
            f"GROUP BY, or wrap it in an aggregate such as SUM or MAX."
        )
    return (
        "A selected column is neither grouped nor aggregated; add it to GROUP BY, or wrap "
        "it in an aggregate such as SUM or MAX."
    )


def _operator(failure: _Failure) -> str | None:
    """A type mismatch, usually the date_key one.

    `date_key` is an integer YYYYMMDD in this schema, so a generator that has
    seen a date dimension elsewhere reaches for a date comparison and gets
    `operator does not exist: integer = date`. That advice is only worth giving
    when date_key is what actually failed -- otherwise it sends the generator
    looking at a join that was never the problem.
    """
    match = re.search(r"operator does not exist:\s*(.+)", failure.message, re.IGNORECASE)
    if not match:
        return None

    operands = match.group(1).splitlines()[0].strip().rstrip(".")
    hint = f"No `{operands}` operator exists: cast one side so both are the same type."
    if "date_key" in failure.lowered or "date_key" in failure.sql.lower():
        hint += " `date_key` is an integer YYYYMMDD in this schema, not a date."
    return hint


def _division_by_zero(failure: _Failure) -> str | None:
    """Only shows on real rows, so it always arrives from the executor."""
    if "division by zero" not in failure.lowered:
        return None
    return (
        "Division by zero: guard the denominator with NULLIF, as in "
        "`numerator / NULLIF(denominator, 0)`."
    )


def _timeout(failure: _Failure) -> str | None:
    """A timeout is the cost problem the planner's estimate failed to catch."""
    timed_out = "statement_timeout" in failure.lowered or "canceling statement due to" in (
        failure.lowered
    )
    if not timed_out:
        return None
    return (
        f"The query was cancelled by the statement timeout, which means it reads far more "
        f"than the question needs. {COST_HINT} Add LIMIT if a sample answers the question."
    )


def _plan_cost(failure: _Failure) -> str | None:
    """The Planner Gate's cost ceiling (section 6.2).

    Matched on the planner's own rejection rather than on any error text,
    because the query is valid here -- it is simply too expensive to run.
    """
    if failure.source != PLANNER or "cost" not in failure.lowered:
        return None
    if not re.search(r"exceed|ceiling|budget|over the", failure.lowered):
        return None
    cost = re.search(r"cost[^\d]*([\d][\d,_.]*)", failure.lowered)
    figure = f" (estimated cost {cost.group(1).rstrip('.')})" if cost else ""
    return f"The estimated plan cost is over the ceiling{figure}. {COST_HINT}"


#: Order matters only in that the cheapest and most specific checks come first;
#: no two rules in the spec's table match the same message.
_RULES = (
    _audit,
    _syntax,
    _group_by,
    _missing_column,
    _missing_table,
    _operator,
    _division_by_zero,
    _timeout,
    _plan_cost,
)


# --- reading the rendered schema ---------------------------------------------


def schema_columns(schema: str) -> list[str]:
    """Every column name in a rendered schema block, in the order it appears.

    The block is `Database.schema_and_samples` output: `=== table ===` headers,
    a `columns:` section of `  name (type, NULL)  -- comment` lines, then
    `keys:` and `sample rows:` sections. Only the columns section is read, so
    `PRIMARY KEY (store_key)` does not become a column called `KEY` and a
    sample row does not become one either.
    """
    names: list[str] = []
    in_columns = False
    for line in schema.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("==="):
            in_columns = False
            continue
        if stripped.rstrip(":").lower() == "columns":
            in_columns = True
            continue
        if stripped.endswith(":") or not line[:1].isspace():
            in_columns = False
            continue
        if in_columns:
            match = re.match(r"([A-Za-z_][\w$]*)\s*\(", stripped)
            if match and match.group(1) not in names:
                names.append(match.group(1))
    return names


def schema_tables(schema: str) -> list[str]:
    """The table names from the `=== name ===` headers of a schema block."""
    return re.findall(r"^===\s*([\w.$]+)\s*===", schema, re.MULTILINE)


# --- small shared helpers -----------------------------------------------------


def _nearest(name: str, candidates: Sequence[str], limit: int = MAX_SUGGESTIONS) -> list[str]:
    """The closest candidate names: difflib first, then containment.

    difflib alone misses the case the spec uses as its own example. `amt`
    against `sales_amt` scores 0.5 on a ratio that divides by total length, so
    a short wrong name never matches the long right one -- yet a wrong name
    that is a whole segment of a real one is precisely the mistake a generator
    makes when it abbreviates. Containment catches those, after the
    similarity matches, which remain the stronger signal.
    """
    if not name or not candidates:
        return []
    ranked = difflib.get_close_matches(name, candidates, n=limit, cutoff=NEAR_MISS_CUTOFF)
    for candidate in candidates:
        if len(ranked) >= limit:
            break
        segments = candidate.split("_")
        if candidate != name and candidate not in ranked and name in segments:
            ranked.append(candidate)
    return ranked


def _quoted(names: Sequence[str]) -> str:
    """`a`, `b` and `c` -- backticked, because these are identifiers."""
    ticked = [f"`{name}`" for name in names]
    if len(ticked) <= 1:
        return "".join(ticked)
    return ", ".join(ticked[:-1]) + f" and {ticked[-1]}"


def _position(message: str) -> int | None:
    """The 0-based character offset a parser reported, whichever way it said it.

    pglast counts from 0 (`at index 9`); PostgreSQL counts from 1 (`POSITION:
    10`, `at character 10`), so the two are not interchangeable and the offset
    is normalised here rather than at each use.
    """
    index = re.search(r"at index (\d+)", message, re.IGNORECASE)
    if index:
        return int(index.group(1))
    character = re.search(r"(?:POSITION:|at character)\s*(\d+)", message, re.IGNORECASE)
    if character:
        return max(0, int(character.group(1)) - 1)
    return None


def _around(sql: str, position: int) -> str:
    """`CONTEXT_CHARS` either side of `position`, flattened onto one line."""
    start = max(0, position - CONTEXT_CHARS)
    end = min(len(sql), position + CONTEXT_CHARS)
    snippet = " ".join(sql[start:end].split())
    return f"{'...' if start > 0 else ''}{snippet}{'...' if end < len(sql) else ''}"


def _failed_sql(history: Sequence[Attempt]) -> str:
    """The most recent attempt's SQL -- the query that just failed."""
    return history[-1].sql if history else ""


def _repeat_prefix(message: str, history: Sequence[Attempt]) -> str:
    """A line naming the earlier attempts that failed this same way, or "".

    Section 6.3's example is a hint that can say "attempts 1 and 2 both joined
    on date_key; that is the error". The join is a specific this module cannot
    derive, so it says only what the history proves: the same error, again, and
    therefore an approach that has to change rather than be adjusted.
    """
    key = message.strip().casefold()
    if not key:
        return ""
    repeats = [
        number
        for number, attempt in enumerate(history, start=1)
        if any(issue.message.strip().casefold() == key for issue in attempt.issues)
    ]
    if not repeats:
        return ""
    numbered = _join_numbers(repeats)
    subject = "Attempt" if len(repeats) == 1 else "Attempts"
    verb = "has" if len(repeats) == 1 else "have"
    return (
        f"{subject} {numbered} {verb} already failed with this same error, so the approach "
        f"itself must change, not just its details. "
    )


def _join_numbers(numbers: Sequence[int]) -> str:
    text = [str(number) for number in numbers]
    if len(text) == 1:
        return text[0]
    return ", ".join(text[:-1]) + f" and {text[-1]}"


def _diagnose(llm: SupportsInvoke, issues: Sequence[Issue], schema: str, sql: str) -> str:
    """The one model call this stage is allowed: a paragraph, never a query.

    A model that is failing or unreachable must not take the run with it. The
    budget decides when to give up; a repair that raised would give up early
    and lose the attempts the user already paid for.
    """
    errors = "\n".join(f"- [{issue.source}] {issue.message}" for issue in issues)
    human = (
        f"Schema:\n{schema.strip() or '(not available)'}\n\n"
        f"The query that failed:\n{sql.strip() or '(not available)'}\n\n"
        f"It was rejected with:\n{errors}\n\n"
        f"Why did this fail, and what must the next attempt do differently?"
    )
    try:
        response = llm.invoke([("system", _DIAGNOSIS_SYSTEM), ("human", human)])
        diagnosis = str(getattr(response, "content", response)).strip()
    except Exception:
        return GENERIC_HINT
    return diagnosis or GENERIC_HINT
